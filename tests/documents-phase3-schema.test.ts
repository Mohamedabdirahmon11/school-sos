import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

const migration = readFileSync(new URL('../supabase/migrations/20261116100000_school_documents_phase3.sql', import.meta.url), 'utf8');
const schema = readFileSync(new URL('../schema.sql', import.meta.url), 'utf8');

test('Phase 3 tables enable RLS and enforce the authenticated school boundary', () => {
  for (const table of ['school_document_versions','school_document_permissions','school_document_audit_events','student_document_attachments']) {
    assert.match(migration, new RegExp('ALTER TABLE public\\.' + table + ' ENABLE ROW LEVEL SECURITY', 'i'));
    assert.match(schema, new RegExp('ALTER TABLE public\\.' + table + ' ENABLE ROW LEVEL SECURITY', 'i'));
  }
  assert.match(migration, /school_id = private\.auth_school_id\(\)/);
  assert.match(migration, /SECURITY DEFINER[\s\S]*SET search_path = ''/);
  assert.match(migration, /schoolos_document_snapshot_and_audit/);
  assert.match(migration, /locked_at IS NOT NULL/);
  assert.match(migration, /student-document-attachments/);
  assert.match(migration, /GRANT EXECUTE ON FUNCTION public\.schoolos_document_snapshot_and_audit\(\) TO service_role/);
});

test('Document history and audit events are generated by a database trigger', () => {
  assert.match(migration, /AFTER INSERT OR UPDATE OR DELETE ON public\.school_documents/);
  assert.match(migration, /INSERT INTO public\.school_document_versions/);
  assert.match(migration, /INSERT INTO public\.school_document_audit_events/);
});
