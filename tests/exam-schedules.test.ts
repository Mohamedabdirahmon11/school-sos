test('exam schedule schema is tenant-scoped and protects room and seat allocations', () => {
  assert.match(migration, /ALTER TABLE public\.exam_schedules ENABLE ROW LEVEL SECURITY/);
  assert.match(migration, /ALTER TABLE public\.exam_seat_assignments ENABLE ROW LEVEL SECURITY/);
  assert.match(migration, /FOREIGN KEY \(class_id, school_id\)/);
  assert.match(migration, /FOREIGN KEY \(subject_id, school_id\)/);
  assert.match(migration, /FOREIGN KEY \(student_id, school_id\)/);
  assert.match(migration, /seat_capacity BETWEEN 1 AND 500/);
  assert.match(migration, /lower\(btrim\(other\.room_name\)\)/);
  assert.match(migration, /other\.class_id = v_schedule\.class_id/);
  assert.match(migration, /ROW_NUMBER\(\) OVER/);
  assert.ok(migration.includes('pg_advisory_xact_lock'));
  assert.match(migration, /SET search_path = ''/);
  assert.match(migration, /REVOKE ALL ON FUNCTION public\.schoolos_publish_exam_schedule/);
  assert.match(migration, /GRANT EXECUTE ON FUNCTION public\.schoolos_publish_exam_schedule/);
  assert.match(shiftMigration, /shift_name VARCHAR\(80\) NOT NULL DEFAULT 'General'/);
  assert.ok(cohortMigration.includes('exam_schedule_cohort_students'));
  assert.ok(cohortMigration.includes('schoolos_set_exam_schedule_cohort'));
  assert.equal((cohortMigration.match(/SECURITY INVOKER/g) || []).length, 2);
  assert.doesNotMatch(cohortMigration, /SECURITY DEFINER/i);
  assert.ok(cohortMigration.includes('is_selected BOOLEAN NOT NULL DEFAULT TRUE'));
  assert.doesNotMatch(cohortMigration, /DELETE FROM public\.exam_schedule_cohort_students/i);
  assert.ok(cohortMigration.includes('teacher already has an overlapping exam'));
  assert.ok(randomizedSeatMigration.includes('md5(cohort.student_id || v_schedule.id)'));
  assert.ok(randomizedSeatMigration.includes('SECURITY INVOKER'));
  assert.match(roomRegistryMigration, /CREATE TABLE IF NOT EXISTS public\.exam_rooms/);
  assert.match(roomRegistryMigration, /capacity INTEGER NOT NULL CHECK \(capacity BETWEEN 1 AND 500\)/);
  assert.match(roomRegistryMigration, /FOREIGN KEY \(room_id, school_id\)/);
  assert.match(roomRegistryMigration, /ALTER TABLE public\.exam_rooms ENABLE ROW LEVEL SECURITY/);
  assert.match(roomRegistryMigration, /ON DELETE RESTRICT/);
  assert.ok(cohortMigration.includes('already have an exam at this time'));
});

